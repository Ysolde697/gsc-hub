  <h1 class="app-pagetitle mb-4">Privacy policy</h1>

  <p class="mb-3">
    gsc-hub is a private, self-hosted dashboard for Google Search Console. It is operated by its owner for
    their own sites and is not offered to the public.
  </p>
  <h2 class="mb-1 mt-4 font-semibold text-ink">What data is accessed</h2>
  <p class="mb-3">
    When the owner connects a Google account, gsc-hub requests access to Google Search Console
    (<code>webmasters</code> scope) to read search performance, sitemaps and URL inspection results for the
    properties of that account, and to resubmit sitemaps on request.
  </p>
  <h2 class="mb-1 mt-4 font-semibold text-ink">How it is stored</h2>
  <p class="mb-3">
    OAuth tokens and settings are stored only in this server's local database. Search Console metrics are
    fetched live and kept only in short-lived memory caches. No data is sold, shared with third parties or
    used for advertising.
  </p>
  <h2 class="mb-1 mt-4 font-semibold text-ink">Removing access</h2>
  <p class="mb-3">
    Deleting an account in gsc-hub revokes its token. Access can also be revoked at any time at
    <a class="text-acc underline" href="https://myaccount.google.com/permissions">myaccount.google.com/permissions</a>.
  </p>
  <p class="mt-6 text-ink-3">Use of information received from Google APIs adheres to the Google API Services User Data Policy, including the Limited Use requirements.</p>
